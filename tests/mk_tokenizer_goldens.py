def cstr(s):
    """A C++ string literal for `s` (UTF-8 bytes, non-ASCII and controls escaped)."""
    out = '"'
    prev_hex = False
    for b in s.encode("utf-8"):
        c = chr(b)
        if c == '"':
            out += '\\"'; prev_hex = False
        elif c == "\\":
            out += "\\\\"; prev_hex = False
        elif c == "\n":
            out += "\\n"; prev_hex = False
        elif c == "\t":
            out += "\\t"; prev_hex = False
        elif 0x20 <= b < 0x7F:
            if prev_hex and c in "0123456789abcdefABCDEF":
                out += '" "'
            out += c; prev_hex = False
        else:
            out += "\\x%02x" % b; prev_hex = True
    return out + '"'


def added(entries):
    return [{"id": i, "content": c, "single_word": False, "lstrip": False, "rstrip": False,
             "normalized": False, "special": sp} for i, c, sp in entries]


def ids_cpp(ids):
    return "{ " + ", ".join(str(i) for i in ids) + " }"


