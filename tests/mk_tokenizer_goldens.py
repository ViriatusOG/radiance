def pretok_case(name, pt):
    """A WordPiece vocabulary of exactly the pieces HF cuts the text into, so the ids name the
    pieces one for one and any other cut shows as [UNK] or a different id."""
    probe = Tokenizer.from_str(json.dumps({
        "pre_tokenizer": pt,
        "model": {"type": "WordPiece", "unk_token": "[UNK]", "continuing_subword_prefix": "##",
                  "max_input_chars_per_word": 100, "vocab": {"[UNK]": 0}}}))
    pieces = [w for w, _ in probe.pre_tokenizer.pre_tokenize_str(PRE_TEXT)]
    vocab = {"[UNK]": 0}
    for w in pieces:
        vocab.setdefault(w, len(vocab))
    js = {"pre_tokenizer": pt,
          "model": {"type": "WordPiece", "unk_token": "[UNK]", "continuing_subword_prefix": "##",
                    "max_input_chars_per_word": 100, "vocab": vocab}}
    tok = Tokenizer.from_str(json.dumps(js))
    ids = tok.encode(PRE_TEXT, add_special_tokens=False).ids
    assert 0 not in ids, (name, pieces)
    return js, pieces, ids


# ---------------------------------------------------------------------------- Gemma-shaped

def gemma_like():
    pieces = ["<pad>", "<eos>", "<bos>", "<unk>", "<mask>", "<start_of_turn>", "<end_of_turn>"]
    pieces += ["<0x%02X>" % b for b in range(256)]
    base = list("abcdefghijklmnopqrstuvwxyz") + [MS, "\n", "\t", "H", "T", ".", ",", "!", "?",
                                                  "é", "'"]
    pieces += base
    merges = [("h", "e"), ("l", "l"), ("he", "ll"), ("hell", "o"), (MS, "w"), ("o", "r"),
              (MS + "w", "or"), ("l", "d"), (MS + "wor", "ld"), (MS, "t"), (MS + "t", "h"),
              (MS + "th", "e"), (MS, "c"), (MS + "c", "a"), (MS + "ca", "t"), (MS, MS),
              (MS + MS, MS + MS), ("\n", "\n"), (MS, "the"), ("t", "h"), ("th", "e"),
              ("i", "n"), ("in", "g"), ("e", "d"), (MS, "a"), (MS, "hello"), ("H", "e"),
              ("He", "ll"), ("Hell", "o"), ("é", "m"), ("o", "j"), ("oj", "i")]
    vocab = {p: i for i, p in enumerate(pieces)}
    for a, b in merges:
        vocab.setdefault(a + b, len(vocab))
    js = {
        "added_tokens": added([(0, "<pad>", True), (1, "<eos>", True), (2, "<bos>", True),
                               (3, "<unk>", True), (4, "<mask>", False),
                               (5, "<start_of_turn>", True), (6, "<end_of_turn>", True)]),
        "normalizer": {"type": "Replace", "pattern": {"String": " "}, "content": MS},
        "pre_tokenizer": {"type": "Split", "pattern": {"String": " "},
                          "behavior": "MergedWithPrevious", "invert": False},
        "post_processor": {"type": "TemplateProcessing",
                           "single": [{"SpecialToken": {"id": "<bos>", "type_id": 0}},
                                      {"Sequence": {"id": "A", "type_id": 0}},
                                      {"SpecialToken": {"id": "<eos>", "type_id": 0}}],
                           "pair": [{"SpecialToken": {"id": "<bos>", "type_id": 0}},
                                    {"Sequence": {"id": "A", "type_id": 0}},
                                    {"SpecialToken": {"id": "<eos>", "type_id": 0}},
                                    {"Sequence": {"id": "B", "type_id": 1}},
                                    {"SpecialToken": {"id": "<eos>", "type_id": 1}}],
                           "special_tokens": {"<bos>": {"id": "<bos>", "ids": [2],
                                                        "tokens": ["<bos>"]},
                                              "<eos>": {"id": "<eos>", "ids": [1],
                                                        "tokens": ["<eos>"]}}},
        "decoder": {"type": "Sequence", "decoders": [
            {"type": "Replace", "pattern": {"String": MS}, "content": " "},
            {"type": "ByteFallback"}, {"type": "Fuse"}]},
        "model": {"type": "BPE", "dropout": None, "unk_token": "<unk>",
                  "continuing_subword_prefix": None, "end_of_word_suffix": None,
                  "fuse_unk": True, "byte_fallback": True, "ignore_merges": False,
                  "vocab": vocab, "merges": [[a, b] for a, b in merges]},
    }
    return js


def mmbert_like():
    """mmBERT's shape (Laya's multilingual checkpoint): the Gemma normaliser that already turns
    spaces into U+2581, then Metaspace(always, split), which prepends U+2581 only to text that does
    not already start with it."""
    js = gemma_like()
    js["pre_tokenizer"] = {"type": "Metaspace", "replacement": MS, "prepend_scheme": "always",
                           "split": True}
    return js


def metaspace_specials(scheme):
    """Metaspace BPE with special tokens: "first" prepends only where the text starts."""
    vocab = {"<s>": 0, "[INST]": 1, MS: 2, "H": 3, "i": 4, MS + "H": 5, "Hi": 6, MS + "Hi": 7,
             "<unk>": 8}
    return {"added_tokens": added([(0, "<s>", True), (1, "[INST]", True)]),
            "pre_tokenizer": {"type": "Metaspace", "replacement": MS, "prepend_scheme": scheme,
                              "split": False},
            "model": {"type": "BPE", "dropout": None, "unk_token": "<unk>",
                      "continuing_subword_prefix": None, "end_of_word_suffix": None,
                      "fuse_unk": False, "byte_fallback": False, "ignore_merges": False,
                      "vocab": vocab, "merges": [[MS, "H"], ["H", "i"], [MS + "H", "i"]]}}


# ---------------------------------------------------------------------------- CLIP-shaped

CLIP_SPLIT = r"""'s|'t|'re|'ve|'m|'ll|'d|[\p{L}]+|[\p{N}]|[^\s\p{L}\p{N}]+"""


def gpt2_alphabet():
    """GPT-2's byte -> character map, in CLIP's vocabulary order."""
    bs = list(range(ord("!"), ord("~") + 1)) + list(range(ord("\xa1"), ord("\xac") + 1)) + \
        list(range(ord("\xae"), ord("\xff") + 1))
    cs = bs[:]
    n = 0
    for b in range(256):
        if b not in bs:
            bs.append(b)
            cs.append(256 + n)
            n += 1
    return [chr(c) for c in cs]


CLIP_TRAIN = ("a photo of a cat, a painting of a dog, best quality, masterpiece, 1girl, solo, "
              "looking at viewer, it's a photograph of the mountains at sunset, don't stop, "
              "highly detailed digital art, portrait of an astronaut riding a horse, ") * 3


def clip_like():
    """CLIP ViT-L/14's tokenizer.json with its vocabulary cut down: the real normaliser, Split,
    ByteLevel, RobertaProcessing and decoder, the 512 byte tokens with and without the "</w>"
    end-of-word suffix in CLIP's order, and merges trained here (most frequent pair, then the
    smallest) over a few prompts, each merged token's id 512 + its rank as in CLIP's own file."""
    from tokenizers import normalizers, pre_tokenizers, Regex
    norm = normalizers.Sequence([normalizers.NFC(), normalizers.Replace(Regex(r"\s+"), " "),
                                 normalizers.Lowercase()])
    pre = pre_tokenizers.Sequence([
        pre_tokenizers.Split(Regex(CLIP_SPLIT), behavior="removed", invert=True),
        pre_tokenizers.ByteLevel(add_prefix_space=False)])
    alpha = gpt2_alphabet()
    vocab = alpha + [c + "</w>" for c in alpha]
    words = {}
    for w, _ in pre.pre_tokenize_str(norm.normalize_str(CLIP_TRAIN)):
        sym = tuple(list(w[:-1]) + [w[-1] + "</w>"])
        words[sym] = words.get(sym, 0) + 1
    merges = []
    for _ in range(160):
        pairs = {}
        for sym, n in words.items():
            for a, b in zip(sym, sym[1:]):
                pairs[(a, b)] = pairs.get((a, b), 0) + n
        if not pairs:
            break
        best = min(pairs, key=lambda k: (-pairs[k], k))
        merges.append(best)
        vocab.append(best[0] + best[1])
        nw = {}
        for sym, n in words.items():
            out, i = [], 0
            while i < len(sym):
                if i + 1 < len(sym) and (sym[i], sym[i + 1]) == best:
                    out.append(sym[i] + sym[i + 1])
                    i += 2
                else:
                    out.append(sym[i])
                    i += 1
            nw[tuple(out)] = nw.get(tuple(out), 0) + n
        words = nw
    bos, eos = len(vocab), len(vocab) + 1
    vocab += ["<|startoftext|>", "<|endoftext|>"]
    return {
        "added_tokens": [
            {"id": bos, "content": "<|startoftext|>", "single_word": False, "lstrip": False,
             "rstrip": False, "normalized": True, "special": True},
            {"id": eos, "content": "<|endoftext|>", "single_word": False, "lstrip": False,
             "rstrip": False, "normalized": False, "special": True}],
        "normalizer": {"type": "Sequence", "normalizers": [
            {"type": "NFC"}, {"type": "Replace", "pattern": {"Regex": r"\s+"}, "content": " "},
            {"type": "Lowercase"}]},
        "pre_tokenizer": {"type": "Sequence", "pretokenizers": [
            {"type": "Split", "pattern": {"Regex": CLIP_SPLIT}, "behavior": "Removed",
             "invert": True},
            {"type": "ByteLevel", "add_prefix_space": False, "trim_offsets": True}]},
        "post_processor": {"type": "RobertaProcessing", "sep": ["<|endoftext|>", eos],
                           "cls": ["<|startoftext|>", bos], "trim_offsets": False,
                           "add_prefix_space": False},
        "decoder": {"type": "ByteLevel", "add_prefix_space": True, "trim_offsets": True},
        "model": {"type": "BPE", "dropout": None, "unk_token": "<|endoftext|>",
                  "continuing_subword_prefix": "", "end_of_word_suffix": "</w>",
                  "fuse_unk": False, "vocab": {t: i for i, t in enumerate(vocab)},
                  "merges": [a + " " + b for a, b in merges]},
    }


